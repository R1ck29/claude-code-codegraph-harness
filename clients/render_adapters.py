#!/usr/bin/env python3
"""Render Claude Code and Codex guidance from one routing policy."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Iterable, Mapping, Sequence

PROJECT_ROOT = Path(__file__).resolve().parents[1]
POLICY_PATH = PROJECT_ROOT / "clients" / "routing-policy.json"
CLAUDE_SKILL_PATH = (
    PROJECT_ROOT
    / "plugins"
    / "codegraph-evaluator"
    / "skills"
    / "code-intelligence"
    / "SKILL.md"
)
ROUTING_REFERENCE_PATH = CLAUDE_SKILL_PATH.parent / "references" / "routing.md"
FRESHNESS_REFERENCE_PATH = CLAUDE_SKILL_PATH.parent / "references" / "freshness.md"
CLAUDE_RULE_PATH = PROJECT_ROOT / "rules" / "codegraph-harness.md"
CODEX_SKILL_PATH = PROJECT_ROOT / "codex" / "skills" / "company-codegraph" / "SKILL.md"


def _bullets(values: Iterable[str], *, code: bool = False) -> str:
    """Return a deterministic Markdown bullet list."""
    if code:
        return "\n".join(f"- `{value}`" for value in values)
    return "\n".join(f"- {value}" for value in values)


def _marker(policy_hash: str) -> str:
    return (
        "<!-- Generated by clients/render_adapters.py; "
        f"routing-policy-sha256: {policy_hash} -->"
    )


def _string_list(policy: Mapping[str, object], key: str) -> list[str]:
    value = policy.get(key)
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise ValueError(f"routing policy {key!r} must be a list of strings")
    return value


def _common_contract(policy: Mapping[str, object]) -> str:
    tools = _string_list(policy, "tools")
    structural_tasks = _string_list(policy, "structural_tasks")
    source_first_tasks = _string_list(policy, "source_first_tasks")
    fallback_conditions = _string_list(policy, "fallback_conditions")
    fallback_tools = _string_list(policy, "fallback_tools")
    expected_boundary = {
        "transport": "registered local gateway only",
        "upstream_access": "never direct",
        "data_egress": "do not send source or graph output to another service",
    }
    if policy.get("gateway_boundary") != expected_boundary:
        raise ValueError("routing policy gateway_boundary is invalid")
    expected_freshness = {
        "query_responses": "authoritative and revalidated on every call",
        "status_tool": "optional diagnostics only",
        "redundant_preflight": "do not call status before a normal query",
    }
    if policy.get("freshness_strategy") != expected_freshness:
        raise ValueError("routing policy freshness_strategy is invalid")

    return f"""## Data boundary

Use only the registered local gateway. Do not register or call an upstream graph backend directly. Do not send source or graph output to another service.

## Allowed graph tools

Only these five read-only gateway tools are in scope:

{_bullets(tools, code=True)}

Every normal query revalidates freshness and returns it in the same response. Inspect that field; do not add a redundant `codegraph_status` preflight. Use `codegraph_status` only for diagnostics when no structural query is otherwise needed. Keep search limits and traversal depth bounded.

## Routing

Use the graph only for structural tasks:

{_bullets(structural_tasks)}

Use {", ".join(f"`{tool}`" for tool in fallback_tools)} and relevant tests first for:

{_bullets(source_first_tasks)}

## Fail-closed fallback

If status or any result is {", ".join(f"**{condition}**" for condition in fallback_conditions)}, stop using graph evidence for the task and fall back to {", ".join(f"`{tool}`" for tool in fallback_tools)}. Do not ask the user to repair graph state during a coding task.

## Evidence boundary

The graph is derived static-analysis data, not source-of-truth. The current source and tests are the source-of-truth. Open consequential source locations and verify relevant tests before proposing or making a change. Clearly separate graph-derived candidates from claims verified in source and tests.

Do not infer runtime behavior from graph structure. Do not claim token or quality improvements unless the current evaluation protocol measured them."""


def render_assets(policy: Mapping[str, object], policy_hash: str) -> dict[Path, str]:
    """Build all generated adapter assets."""
    marker = _marker(policy_hash)
    contract = _common_contract(policy)

    claude_skill = f"""---
name: code-intelligence
description: Use the approved local codegraph gateway for bounded structural code exploration, then verify consequential claims against source and tests.
argument-hint: "[structural code question]"
---
{marker}

# Code intelligence routing

Apply this skill only when the question is structural. The configured approved code-graph MCP is a local gateway; the presence of this skill alone does not prove that the gateway or its index is usable.

{contract}

Read [routing guidance](references/routing.md) and [freshness requirements](references/freshness.md) before treating graph output as evidence.
"""

    claude_rule = f"""{marker}

# Code intelligence harness rule

Apply this rule to the approved code-graph MCP. It does not grant approval to any other backend or network service.

{contract}

Never disable normal source exploration or tests to force graph use.
"""

    codex_skill = f"""---
name: company-codegraph
description: Use the approved local codegraph gateway for bounded structural code exploration in Codex, then verify consequential claims against source and tests.
---
{marker}

# Company codegraph for Codex

This file is the distributable source for the user skill installed at `$HOME/.agents/skills/company-codegraph/SKILL.md`. It does not modify a global or project `AGENTS.md`.

Apply this skill only when the question is structural. The configured MCP server is a local gateway; this skill does not register the server and does not prove that its index is usable.

{contract}

Never disable normal source exploration or tests to force graph use.
"""

    routing_reference = f"""{marker}

# Routing guidance

{contract}
"""

    freshness_reference = f"""{marker}

# Freshness requirements

Every `codegraph_search`, `codegraph_neighbors`, `codegraph_impact`, and `codegraph_architecture` call revalidates freshness and returns it in the same response. Inspect that field. Do not call `codegraph_status` as a routine preflight; use it only for diagnostics when no structural query is otherwise needed.

A result is usable only when the gateway reports a successful current index for the open workspace. If the result is **unavailable**, **stale**, **dirty**, or **truncated**, stop using graph evidence and fall back to `Read`, `Grep`, `LSP`, and relevant tests.

The graph is derived static-analysis data, not source-of-truth. The current source and tests are the source-of-truth.
"""

    return {
        CLAUDE_SKILL_PATH: claude_skill,
        CLAUDE_RULE_PATH: claude_rule,
        CODEX_SKILL_PATH: codex_skill,
        ROUTING_REFERENCE_PATH: routing_reference,
        FRESHNESS_REFERENCE_PATH: freshness_reference,
    }


def _load_policy() -> tuple[Mapping[str, object], str]:
    policy_bytes = POLICY_PATH.read_bytes()
    policy = json.loads(policy_bytes)
    if not isinstance(policy, dict):
        raise ValueError("routing policy must be a JSON object")
    return policy, hashlib.sha256(policy_bytes).hexdigest()


def _check(assets: Mapping[Path, str]) -> int:
    stale = []
    for path, expected in assets.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            stale.append(path.relative_to(PROJECT_ROOT))
    if stale:
        for path in stale:
            print(f"stale generated adapter: {path}", file=sys.stderr)
        return 1
    return 0


def _write(assets: Mapping[Path, str]) -> int:
    for path, content in assets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if committed adapter files differ from the canonical policy",
    )
    args = parser.parse_args(argv)
    policy, policy_hash = _load_policy()
    assets = render_assets(policy, policy_hash)
    return _check(assets) if args.check else _write(assets)


if __name__ == "__main__":
    raise SystemExit(main())
